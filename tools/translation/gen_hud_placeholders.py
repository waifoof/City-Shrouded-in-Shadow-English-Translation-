"""Regenerate hud_placeholders_tl.py from a remaining-Japanese scan (leftover JSON list)."""
import json, sys, struct
sys.path[:0] = ['.', sys.argv[2]]
from game_text import unwrap
from leftovers_tl import hud_en
import hud_tl
rows = json.load(open(sys.argv[1], encoding='utf-8'))
O = sys.argv[3]
H, skipped = {}, []
for x in rows:
    if x['kind'] != 'hud': continue
    p, o = x['path'], int(x['key_or_offset'])
    body = unwrap(open(O + '/' + p.removeprefix('common/'), 'rb').read())
    n = struct.unpack_from('<I', body, o - 4)[0]
    try: jp = body[o:o + n].decode('utf-8')
    except UnicodeDecodeError: skipped.append((p, o, 'damaged bytes')); continue
    e = hud_en(jp)
    if e is None or len(e.encode()) > n: skipped.append((p, o, jp[:40])); continue
    if o in hud_tl.H.get(p, {}): continue
    H.setdefault(p, {})[o] = e
with open('hud_placeholders_tl.py', 'w', encoding='utf-8') as f:
    f.write('# Generated by gen_hud_placeholders.py: HUD placeholder/default strings (the game\n# replaces them at runtime). Left alone: strings with damaged bytes in the original.\nH = {\n')
    for p in sorted(H):
        f.write(f' {p!r}: {{\n' + ''.join(f'  {o}: {H[p][o]!r},\n' for o in sorted(H[p])) + ' },\n')
    f.write('}\n')
print(sum(map(len, H.values())), 'HUD strings;', len(skipped), 'skipped')
for s in skipped: print(' skip', s)
